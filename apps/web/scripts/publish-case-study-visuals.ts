/** Upload the curated diagrams and existing public screenshots, then record immutable URLs. */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PutObjectCommand, HeadObjectCommand } from "@aws-sdk/client-s3";
import { caseStudyVisuals } from "../lib/constants/case-study-visuals";
import { buildR2PublicUrl } from "../lib/functions/r2-public-url";
import {
  createR2Client,
  fingerprint,
  loadEnvFile,
  requireR2Env,
} from "./lib/cover-backfill";

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
await loadEnvFile(path.join(appDir, ".env.local"));
await loadEnvFile(path.join(appDir, ".env"));
requireR2Env();
const apply = process.argv.includes("--apply");
const client = createR2Client();
const urls: Record<string, string> = {};
for (const [id, visual] of Object.entries(caseStudyVisuals)) {
  const bytes = await readFile(path.join(appDir, "public", visual.localSrc));
  const ext = path.extname(visual.localSrc);
  const key = `case-study-visuals/${id}-${fingerprint(bytes)}${ext}`;
  const url = buildR2PublicUrl(key);
  if (apply) {
    let exists = false;
    try {
      await client.send(
        new HeadObjectCommand({ Bucket: process.env.R2_BUCKET_NAME, Key: key }),
      );
      exists = true;
    } catch (error: any) {
      if (
        error?.$metadata?.httpStatusCode !== 404 &&
        error?.name !== "NotFound"
      )
        throw error;
    }
    // Content-addressed keys are immutable: never overwrite an existing object.
    if (!exists)
      await client.send(
        new PutObjectCommand({
          Bucket: process.env.R2_BUCKET_NAME,
          Key: key,
          Body: bytes,
          ContentType: ext === ".svg" ? "image/svg+xml" : "image/png",
          CacheControl: "public, max-age=31536000, immutable",
          Metadata: { purpose: "case-study-editorial-visual" },
        }),
      );
    const response = await fetch(url, { method: "HEAD" });
    if (!response.ok)
      throw new Error(
        `Public image check failed for ${id}: ${response.status}`,
      );
  }
  urls[id] = url;
  console.log(
    `${apply ? "Verified" : "Preview"} ${id} (${bytes.length} bytes)`,
  );
}
if (apply) {
  await writeFile(
    path.join(appDir, "lib/constants/case-study-assets.ts"),
    `/** Public asset URLs, generated by scripts/publish-case-study-visuals.ts. */\nexport const publishedCaseStudyAssets: Record<string, string> = ${JSON.stringify(urls, null, 2)};\n`,
  );
  console.log(
    "Published URLs saved. The case-study refresh can now embed them in the CMS.",
  );
}
